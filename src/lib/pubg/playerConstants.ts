// 플레이어 한 명을 조회할 때 쓰는 TTL.
//
// 전적·통계 페이지가 한 번에 PUBG 호출 4회를 쓴다(닉네임 → id + 세 종류). 분당 한도가
// 10회라 **캐시가 없으면 두 사람만 봐도 막힌다.** 아래 값들이 그 방패다.
//
// `fetchPubgCached`의 기본 TTL은 60초다. 그건 "정하지 않았다"는 뜻이지 적절하다는 뜻이
// 아니므로, 플레이어 조회는 전부 여기서 값을 정해 넘긴다 — 빠뜨리면 조용히 60초가 된다.

/**
 * 갱신 버튼("전적 업데이트")이 눌리기까지의 대기 — 5분.
 *
 * 아래 두 TTL이 이 값에 맞춰져 있다. 버튼이 풀렸는데 캐시가 살아 있으면 눌러도 같은 값이
 * 나오므로, **갱신 대상의 TTL은 이 값보다 반드시 짧아야 한다.**
 * 실제 대기 시간은 `UpdateButton.tsx`가 갖고 있다 — 클라이언트에서 세는 값이라 여기 둘 수 없다.
 */
const UPDATE_COOLDOWN = 60 * 5;

/**
 * 갱신 대상 TTL — 4분.
 *
 * 쿨다운(5분)보다 1분 짧다. 같게 두면 안 된다 — **두 타이머의 시작점이 다르기 때문이다.**
 * 쿨다운은 사용자가 마지막으로 누른 시각부터 세고, 캐시 TTL은 캐시가 쓰인 시각부터 센다.
 * 내가 페이지를 연 뒤 다른 사람이 같은 플레이어를 조회하면 캐시가 그때 새로 쓰여서,
 * 내 쿨다운이 풀릴 때 캐시가 아직 살아 있다. 그 여유가 이 1분이다.
 *
 * 아래로는 못 내린다. PUBG는 매치가 끝나고 API에 뜨기까지 시간이 걸리는데(1분 안팎),
 * **그보다 짧은 TTL은 "아직 없는 것"을 확인하러 한도를 쓴다.** 지연보다 짧게 잡으면
 * 새로고침할 때마다 헛호출이 나가고, 정작 매치는 그다음 호출에서야 보인다.
 */
export const PLAYER_REFRESH_TTL = UPDATE_COOLDOWN - 60;

/**
 * 닉네임 → 계정 id TTL — 24시간.
 *
 * **매치 목록을 떼어 낸 것에만 쓴다.** PUBG의 `players` 응답에는 최근 매치 id가 함께 실려
 * 오는데(그게 최근 전적의 유일한 출처다), 응답 전체를 하루 잡아 두면 전적 목록이 하루 동안
 * 얼어붙는다. 닉네임과 id의 연결만 오래 사는 것이지 응답 전체가 그런 게 아니다.
 *
 * 놓아준 닉네임을 남이 이어받으면 최대 하루 동안 엉뚱한 사람이 뜬다. 드물어서 받아들인다 —
 * 계정 id 자체는 안 변하므로 "내 전적이 안 보인다"는 생기지 않는다.
 */
export const PLAYER_ID_TTL = 60 * 60 * 24;

/** 매치 관계를 뗀 응답의 스키마 버전. 담는 필드를 바꾸면 올릴 것. */
export const PLAYER_ID_SCHEMA_VERSION = "v1";

/**
 * 시즌 스탯(랭크·일반) TTL — 갱신 대상이라 4분.
 *
 * 통산 스탯(10분)과 값이 다른 이유는 성격이 달라서다. 시즌 스탯은 사용자가 "방금 판 결과"를
 * 기대하는 값이고 갱신 버튼이 약속하는 대상이다. 통산은 한 판으로 거의 안 움직인다.
 */
export const SEASON_STATS_TTL = PLAYER_REFRESH_TTL;

/**
 * 통산 스탯 TTL — 10분.
 *
 * 매치를 뛰면 값이 오르므로 마스터리보다는 짧게 잡는다. 다만 통산 수치는 한 판으로 거의
 * 움직이지 않아(킬 1,455 중 +2 같은 식) 초 단위로 맞출 이유가 없다.
 */
export const LIFETIME_TTL = 60 * 10;

/**
 * 무기·생존 숙련도 TTL — 1시간.
 *
 * 레벨과 누적 XP라 훨씬 천천히 변한다. 짧게 잡아 봐야 같은 값을 다시 받아오며 한도만 쓴다.
 */
export const MASTERY_TTL = 60 * 60;

/**
 * 통산 스탯 요약 버전. 담는 필드를 바꾸면 올릴 것.
 *
 * 원본 35개 중 26개만 캐시하므로, 뺐던 필드를 다시 넣으면 옛 요약에는 그 값이 없다.
 */
export const LIFETIME_SCHEMA_VERSION = "v1";
