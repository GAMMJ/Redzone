// 플레이어 한 명을 조회할 때 쓰는 TTL.
//
// 전적·통계 페이지가 한 번에 PUBG 호출 4회를 쓴다(닉네임 → id + 세 종류). 분당 한도가
// 10회라 **캐시가 없으면 두 사람만 봐도 막힌다.** 아래 값들이 그 방패다.
//
// `fetchPubgCached`의 기본 TTL은 60초다. 그건 "정하지 않았다"는 뜻이지 적절하다는 뜻이
// 아니므로, 플레이어 조회는 전부 여기서 값을 정해 넘긴다 — 빠뜨리면 조용히 60초가 된다.

/**
 * 닉네임 → 계정 id TTL — 24시간.
 *
 * 이 연결은 개명이 아니면 안 변한다. 그런데 전적·통계 양쪽이 화면을 열 때마다 이 호출로
 * 한도를 한 번씩 썼다(기본값 60초라 사실상 매번 새로 불렀다).
 *
 * 놓아준 닉네임을 남이 이어받으면 최대 하루 동안 엉뚱한 사람이 뜬다. 드물어서 받아들인다 —
 * 계정 id 자체는 안 변하므로 "내 전적이 안 보인다"는 생기지 않는다.
 */
export const PLAYER_ID_TTL = 60 * 60 * 24;

/**
 * 시즌 스탯(랭크·일반) TTL — 10분.
 *
 * 통산 스탯과 같은 값이다. 근거도 같다 — 한 판으로 거의 안 움직인다.
 * 이 둘도 값을 안 넘겨 기본값 60초를 쓰고 있었다.
 */
export const SEASON_STATS_TTL = 60 * 10;

/**
 * 통산 스탯 TTL — 10분.
 *
 * 매치를 뛰면 값이 오르므로 마스터리보다는 짧게 잡는다. 다만 통산 수치는 한 판으로 거의
 * 움직이지 않아(킬 1,455 중 +2 같은 식) 초 단위로 맞출 이유가 없다.
 */
export const LIFETIME_TTL = 60 * 10;

/**
 * 무기·생존 숙련도 TTL — 1시간.
 *
 * 레벨과 누적 XP라 훨씬 천천히 변한다. 짧게 잡아 봐야 같은 값을 다시 받아오며 한도만 쓴다.
 */
export const MASTERY_TTL = 60 * 60;

/**
 * 통산 스탯 요약 버전. 담는 필드를 바꾸면 올릴 것.
 *
 * 원본 35개 중 26개만 캐시하므로, 뺐던 필드를 다시 넣으면 옛 요약에는 그 값이 없다.
 */
export const LIFETIME_SCHEMA_VERSION = "v1";
